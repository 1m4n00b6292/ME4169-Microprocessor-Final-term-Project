/* Draw one 6x8 cell (scaled). CS must already be low. */
static void draw_char(uint8_t x, uint8_t y, char c,
                      uint16_t fg, uint16_t bg, uint8_t sz)
{
    uint8_t col[5];
    uint8_t i;
    if (c < 32 || c > 126) c = '?';
    for (i = 0; i < 5; i++)
        col[i] = pgm_read_byte(&font5x7[(uint16_t)(c - 32) * 5 + i]);

    uint8_t fh = fg >> 8, fl = (uint8_t)fg;
    uint8_t bh = bg >> 8, bl = (uint8_t)bg;

    set_window(x, y, x + 6 * sz - 1, y + 8 * sz - 1);

    for (uint8_t row = 0; row < 8; row++) {
        for (uint8_t ry = 0; ry < sz; ry++) {
            for (uint8_t cx = 0; cx < 6; cx++) {
                uint8_t on = (cx < 5) && (row < 7) && ((col[cx] >> row) & 1);
                uint8_t hi = on ? fh : bh;
                uint8_t lo = on ? fl : bl;
                for (uint8_t rx = 0; rx < sz; rx++) {
                    spi_tx(hi);
                    spi_tx(lo);
                }
            }
        }
    }
}

static uint8_t put_str(uint8_t x, uint8_t y, const char *s,
                       uint16_t fg, uint16_t bg, uint8_t sz, uint8_t from_flash)
{
    if (!sz || y + 8 * sz > TFT_H) return x;
    CS_LOW();
    for (;;) {
        char c = from_flash ? (char)pgm_read_byte(s) : *s;
        if (!c) break;
        s++;
        if ((uint16_t)x + 6 * sz > TFT_W) break;
        draw_char(x, y, c, fg, bg, sz);
        x += 6 * sz;
    }
    CS_HIGH();
    return x;
}

uint8_t tft_text(uint8_t x, uint8_t y, const char *s,
                 uint16_t fg, uint16_t bg, uint8_t size)
{
    return put_str(x, y, s, fg, bg, size, 0);
}

uint8_t tft_text_P(uint8_t x, uint8_t y, const char *s,
                   uint16_t fg, uint16_t bg, uint8_t size)
{
    return put_str(x, y, s, fg, bg, size, 1);
}

uint8_t tft_int(uint8_t x, uint8_t y, int16_t v, uint8_t width,
                uint16_t fg, uint16_t bg, uint8_t size)
{
    char buf[8];
    char *p = buf + 7;
    uint16_t u = (v < 0) ? (uint16_t)(0u - (uint16_t)v) : (uint16_t)v;

    *p = 0;
    do { *--p = '0' + (u % 10); u /= 10; } while (u);
    if (v < 0) *--p = '-';

    uint8_t len = (uint8_t)((buf + 7) - p);
    x = put_str(x, y, p, fg, bg, size, 0);
    while (len++ < width && width <= 7)
        x = put_str(x, y, " ", fg, bg, size, 0);
    return x;
}